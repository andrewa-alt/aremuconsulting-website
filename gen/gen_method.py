#!/usr/bin/env python3
"""Generate the signature diagrams for the Aremu Consulting site
(DESIGN.md §4.3 / §5 contract).

Reads parts/tokens.json for colors/fonts and writes:
  build/assets/method.svg  — the named method as 4 flat drafting-sheet
      blocks stacked on a vertical rail (Discover -> Scope ->
      Milestones -> Handover). Faint blueprint grid + registration ticks.
  (the hero "what you leave the call with" offer is plain HTML in
   parts/pages/index.html, animated in styles.css — not an SVG)

All text is word-wrapped and blocks sized to content. Generated by script
from token data (never hand-pasted into HTML); build.py reads the .svg
files and inlines them by file read.

Usage: python3 gen/gen_method.py
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOKENS_PATH = os.path.join(ROOT, "parts", "tokens.json")
OUT_DIR = os.path.join(ROOT, "build", "assets")

with open(TOKENS_PATH, "r", encoding="utf-8") as fh:
    TOKENS = json.load(fh)
C = TOKENS["colors"]
MONO = "Martian Mono, Cascadia Code, SF Mono, Menlo, Consolas, monospace"
BODY = "Atkinson Hyperlegible, Segoe UI, system-ui, sans-serif"

MONO_ADV = 6.6   # 11px mono
BODY_ADV = 7.0   # 12.5px sans


def esc(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def wrap(text, max_chars):
    words = text.split()
    lines, cur = [], ""
    for w in words:
        candidate = (cur + " " + w).strip()
        if len(candidate) <= max_chars:
            cur = candidate
        else:
            if cur:
                lines.append(cur)
            if len(w) <= max_chars:
                cur = w
            else:
                lines.append(w[:max_chars])
                cur = w[max_chars:]
    if cur:
        lines.append(cur)
    return lines


def svg_open(width, height, title, desc, prefix):
    """SVG wrapper with UNIQUE ids per diagram so aria-labelledby never
    collides when multiple SVGs are inlined on one page (QA P1).
    Note: each stage sheet is a top-level <g class="sheet"> sibling and the
    only <g> elements, so CSS `g.sheet:nth-of-type(n)` maps 1:1 to stages."""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" '
        f'aria-labelledby="{prefix}-title {prefix}-desc">'
        f"\n<title id=\"{prefix}-title\">{esc(title)}</title>"
        f"\n<desc id=\"{prefix}-desc\">{esc(desc)}</desc>"
    )


def grid_defs():
    """Blueprint grid pattern (faint) + registration tick marker."""
    return (
        f'<defs>'
        f'<pattern id="bp" width="22" height="22" patternUnits="userSpaceOnUse">'
        f'<path d="M 22 0 L 0 0 0 22" fill="none" stroke="{C["grid"]}" stroke-width="1"/>'
        f'</pattern>'
        f'<marker id="arr" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">'
        f'<path d="M 0 0 L 10 5 L 0 10 z" fill="{C["accent"]}"/>'
        f'</marker>'
        f'</defs>'
    )


def render_method():
    """Four vertical-rail drafting sheets (the signature)."""
    rail_x = 34
    sheet_x = 62
    sheet_w = 830
    labels_x = sheet_x + 26
    text_w = sheet_w - 52
    body_max = int(text_w / BODY_ADV)
    mono_max = int(text_w / MONO_ADV)

    stages = [
        ("01", "Discover",
         "Understand the problem before the first fix.",
         [("input", "brief · current state"),
          ("what happens", "A working session on the problem, constraints, and the systems you already run."),
          ("you receive", "written problem statement · fit assessment"),
          ("handoff", "scope brief")]),
        ("02", "Scope",
         "Scope frozen in writing. Changes priced before done.",
         [("input", "discovery outputs"),
          ("what happens", "Deliverables, architecture direction, and explicit out-of-scope, written down and agreed."),
          ("you receive", "written scope · milestone map · pricing shape"),
          ("handoff", "signed scope")]),
        ("03", "Milestones",
         "Fixed-price milestones. Nothing drifts.",
         [("input", "signed scope"),
          ("what happens", "The build is split into milestones with a defined done state and a review at every gate."),
          ("you receive", "milestone plan · change-pricing policy"),
          ("handoff", "accepted milestones")]),
        ("04", "Handover",
         "Ships as a system, not a deliverable.",
         [("input", "accepted milestones"),
          ("what happens", "Code, docs, tests and a handover session; maintenance offered at handover, not a squeeze."),
          ("you receive", "code · docs · tests · handover session"),
          ("handoff", "production + maintenance decision")]),
    ]

    row_h = 178
    sheet_h = 150
    gap = 24
    rail_top = 40
    H = rail_top + len(stages) * row_h + 40

    parts = [
        svg_open(920, H,
                 "The named delivery method: Discover, Scope, Milestones, Handover",
                 "Four drafting-sheet stages stacked on a vertical rail, each showing input, what happens, what you receive, and the handoff artifact.",
                 "sig-method"),
        grid_defs(),
        # rail
        f'<line x1="{rail_x}" y1="{rail_top}" x2="{rail_x}" y2="{rail_top + len(stages) * row_h - 24}" stroke="{C["rule"]}" stroke-width="2"/>',
    ]
    for i, (num, name, thesis, rows) in enumerate(stages):
        y = rail_top + i * row_h
        parts.append(f'<g class="sheet">')
        # node dot on rail
        parts.append(f'<rect x="{rail_x - 5}" y="{y + 14}" width="10" height="10" fill="{C["accent"]}"/>')
        # sheet — grid comes from the fill overlay only (single source, QA P3)
        parts.append(
            f'<rect x="{sheet_x}" y="{y}" width="{sheet_w}" height="{sheet_h}" fill="{C["sheet"]}" '
            f'stroke="{C["rule"]}" stroke-width="1"/>'
        )
        parts.append(f'<rect x="{sheet_x}" y="{y}" width="{sheet_w}" height="{sheet_h}" fill="url(#bp)" opacity="0.5" pointer-events="none"/>')
        # stage chip + code
        parts.append(f'<rect x="{labels_x}" y="{y + 20}" width="12" height="12" fill="{C["accent"]}"/>')
        parts.append(
            f'<text x="{labels_x + 22}" y="{y + 32}" font-family="{MONO}" font-size="12" '
            f'letter-spacing="2.5" fill="{C["accent"]}" font-weight="600">STAGE {num} · {esc(name.upper())}</text>'
        )
        # input meta right
        parts.append(
            f'<text x="{sheet_x + sheet_w - 26}" y="{y + 32}" text-anchor="end" font-family="{MONO}" '
            f'font-size="10.5" fill="{C["muted"]}">input: {esc(rows[0][1])}</text>'
        )
        # thesis (sans)
        parts.append(
            f'<text x="{labels_x}" y="{y + 62}" font-family="{BODY}" font-size="15.5" font-weight="700" fill="{C["ink"]}">{esc(thesis)}</text>'
        )
        # rows
        ry = y + 92
        for key, val in rows[1:]:
            parts.append(
                f'<text x="{labels_x}" y="{ry}" font-family="{MONO}" font-size="10" letter-spacing="1.2" '
                f'transform="rotate(0)" fill="{C["muted"]}">{esc(key.upper())}</text>'
            )
            key_w = len(key) * 7 + 4
            lines = wrap(val, mono_max - 22)
            lx = labels_x + 110
            for line in lines:
                parts.append(
                    f'<text x="{lx}" y="{ry}" font-family="{MONO}" font-size="10.5" fill="{C["ink-soft"]}">{esc(line)}</text>'
                )
                ry += 15
            ry += 2
        if i < len(stages) - 1:
            ax = sheet_x + sheet_w / 2
            ay = y + sheet_h + gap / 2
            parts.append(
                f'<line x1="{ax - 16}" y1="{ay}" x2="{ax + 16}" y2="{ay}" stroke="{C["accent"]}" '
                f'stroke-width="2" marker-end="url(#arr)"/>'
            )
        parts.append(f'</g>')
    parts.append("</svg>")
    return "\n".join(parts)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for fname, render in (
        ("method.svg", render_method),
    ):
        payload = render()
        path = os.path.join(OUT_DIR, fname)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(payload)
        print("wrote", path, f"({len(payload)} bytes)")


if __name__ == "__main__":
    main()